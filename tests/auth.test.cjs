// Testes de comportamento sem dependências. O DOM simulado não substitui a revisão visual.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const sessionKey = 'makerlink.session.v1';
const accountsKey = 'makerlink.accounts.v1';

const { boot, registration } = require('./helpers.cjs');

let app = boot();
assert.equal(app.context.location.hash, '#boas-vindas');
assert.equal(app.element('#sidebar').hidden, true);
app.navigate('conexoes');
assert.equal(app.context.location.hash, '#boas-vindas');
app.navigate('2fa');
assert.equal(app.context.location.hash, '#login');
app.submit('register-form');
assert.equal(app.element('full-name').attributes['aria-invalid'], 'true');
registration(app, { username: 'x', email: 'inválido', password: 'senha-real' });
app.element('terms').checked = false;
app.element('privacy').checked = false;
app.submit('register-form');
for (const id of ['username', 'email', 'password', 'confirm-password', 'terms', 'privacy']) assert.equal(app.element(id).attributes['aria-invalid'], 'true');
registration(app);
app.submit('register-form');
assert.equal(app.context.location.hash, '2fa');
assert.equal(app.storage.has(sessionKey), false, '2FA deve preceder a sessão');
app.element('code').value = '123';
app.submit('two-factor-form');
assert.match(app.element('code-error').textContent, /seis/);
app.element('code').value = '000000';
app.submit('two-factor-form');
assert.match(app.element('code-error').textContent, /incorreto/);
assert.equal(app.storage.has(sessionKey), false);
app.element('code').value = '123456';
app.submit('two-factor-form');
assert.equal(app.context.location.hash, 'onboarding/boas-vindas');
assert.equal(app.auth.user().initials, 'AM');
assert.match(app.context.feedback, /concluída/);
assert.equal(JSON.parse(app.storage.get(accountsKey)).length, 1);
assert(!JSON.stringify([...app.storage.values()]).includes('Maker123!'));
assert(!app.storage.get(accountsKey).includes('password'));
app.navigate('onboarding');
assert.match(app.element('#auth-main').innerHTML, /Bem-vindo, Ana/);
// A regressão das rotas anteriores começa depois do onboarding obrigatório.
app.storage.set('makerlink.onboarding.v1.ana_maker', JSON.stringify({ interests: ['eletronica'], experience: 'iniciante', communities: [], step: 5, completed: true }));
for (const route of app.context.window.MakerLinkData.navigation) {
  app.navigate(route.id);
  assert.equal(app.context.location.hash, `#${route.id}`);
  assert.equal(app.element('.workspace').hidden, false);
  assert(app.context.document.title.includes(route.label));
}
assert.equal(app.element('.user-button strong').textContent, 'Ana Maker');
assert.equal(app.element('.topbar .avatar').textContent, 'AM');
app.navigate('inicio');
assert.match(app.element('#main').innerHTML, /Olá, Ana/);
const stored = app.storage;
app = boot(stored);
assert.equal(app.context.location.hash, '#inicio', 'recarregar deve restaurar sessão');
app.click('#logout');
assert.equal(app.auth.user(), null);
assert(!stored.has(sessionKey));
app.navigate('inicio');
assert.equal(app.context.location.hash, '#boas-vindas');
registration(app);
app.submit('register-form');
assert.match(app.element('username-error').textContent, /já/);
assert.match(app.element('email-error').textContent, /já/);
app.element('identity').value = 'ana_maker';
app.element('password').value = 'incorreta';
app.submit('login-form');
assert.match(app.element('login-form .form-error').textContent, /incorretos/);
app.element('password').value = 'Maker123!';
app.element('remember').checked = true;
app.submit('login-form');
assert.equal(app.context.location.hash, '2fa');
app.element('code').value = '123456';
app.submit('two-factor-form');
assert.equal(app.context.location.hash, 'inicio');
let session = JSON.parse(stored.get(sessionKey));
assert(Math.abs(session.expires - Date.now() - 30 * 86400000) < 2000);
app.click('#logout');
app.element('identity').value = 'ANA@EXAMPLE.COM';
app.element('remember').checked = false;
app.submit('login-form');
app.submit('two-factor-form');
session = JSON.parse(stored.get(sessionKey));
assert(Math.abs(session.expires - Date.now() - 86400000) < 2000);
session.expires = Date.now() - 1;
stored.set(sessionKey, JSON.stringify(session));
app = boot(stored);
assert.equal(app.auth.user(), null);
app.click('#demo-login');
assert.equal(app.auth.user().name, 'Eduardo Costa');
assert.equal(app.context.location.hash, 'inicio');
app.click('#recover-password');
assert.match(app.context.modal.text, /Nenhum e-mail/);
app.element('password').type = 'password';
app.click('[data-password]', { dataset: { password: 'password' }, setAttribute() {} });
assert.equal(app.element('password').type, 'text');
app = boot(new Map([[accountsKey, '{invalid'], [sessionKey, '{}']]));
assert.equal(app.auth.user(), null);
app = boot(new Map(), true);
app.click('#demo-login');
assert.equal(app.auth.user(), null);
assert.match(app.context.modal.title, /indisponível/);
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
for (const [, reference] of html.matchAll(/(?:src|href)="([^"#]+)"/g)) assert(fs.existsSync(path.join(root, reference)), reference);
console.log('PASS: validações, cadastro → 2FA → onboarding, login por usuário/e-mail, códigos inválidos, sessão/restauração/expiração, lembrar de mim, logout, demo, oito rotas, identidade, armazenamento corrompido/bloqueado e referências locais.');
