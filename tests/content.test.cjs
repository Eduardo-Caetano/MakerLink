const before = Date.now();
submit();
const saved = JSON.parse(storage.get(postKey));
assert.equal(saved.length, 1);
assert.equal(saved[0].authorUsername, user.username);
assert.equal(saved[0].categoryId, 'arduino');
assert.deepEqual(saved[0].tags, ['ESP32', 'sensores']);
assert(Date.parse(saved[0].createdAt) >= before);
assert.equal(saved[0].title, 'Meu primeiro sensor');
assert(!storage.get(postKey).includes(user.email));
assert.match(app.context.feedback, /Publicação criada/);
app.navigate('inicio');
assert.match(app.element('#main').innerHTML, /Meu primeiro sensor/);
assert.equal(app.context.window.MakerLinkFeed.ordered(user)[0].id, saved[0].id);
assert.equal(app.context.window.MakerLinkContent.all(user).length, 8);
assert.equal(app.context.window.MakerLinkData.posts.length, 7);
const ownPost = app.context.window.MakerLinkContent.own(user)[0];
assert.equal(ownPost.author, 'Ana Maker');
assert.equal(ownPost.likes, 0);
assert.equal(ownPost.comments.length, 0);
assert.equal(ownPost.community, 'Arduino e ESP32');
assert.match(app.element('#main').innerHTML, /href="#perfil"/);
app.navigate('perfil');
assert.match(app.element('#main').innerHTML, /Meu primeiro sensor/);
assert.equal(app.context.window.MakerLinkProfiles.resolve('perfil', user).publications.length, 1);
assert.equal(app.auth.user().level, 'Aprendiz');
app = boot(storage);
app.navigate('perfil');
assert.match(app.element('#main').innerHTML, /Meu primeiro sensor/);
assert.equal(app.context.window.MakerLinkContent.own(user).length, 1, 'Persiste ao reiniciar os scripts');
for (const type of ['Dúvida técnica', 'Tutorial']) {
  app.navigate('publicar');
  fill({ 'post-type': type, 'post-title': `<img src=x onerror=alert(1)> ${type}`, 'post-tags': '' });
  submit();
}
const records = JSON.parse(storage.get(postKey));
assert.equal(records.length, 3);
assert.equal(new Set(records.map(record => record.id)).size, 3);
assert(records.slice(1).every(record => record.tags.length === 0));
app.navigate('inicio');
assert.match(app.element('#main').innerHTML, /&lt;img src=x/);
assert(!app.element('#main').innerHTML.includes('<img src=x'));
app.navigate('perfil');
assert(!app.element('#main').innerHTML.includes('<img src=x'));
const other = { ...user, username: 'outro' };
assert.equal(app.context.window.MakerLinkContent.own(other).length, 0, 'Separa publicações por conta');
assert.equal(app.context.window.MakerLinkContent.all(other).length, 7);
app.navigate('publicar');
fill();
const originalSet = app.context.localStorage.setItem;
