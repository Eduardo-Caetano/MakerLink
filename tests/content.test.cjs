const assert = require('node:assert/strict');
const { boot } = require('./helpers.cjs');
const user = { name: 'Ana Maker', username: 'ana_maker', initials: 'AM', email: 'ana@example.com' };
const storage = new Map([
  ['makerlink.session.v1', JSON.stringify({ user, expires: Date.now() + 86400000 })],
  ['makerlink.onboarding.v1.ana_maker', JSON.stringify({ interests: ['arduino'], communities: ['arduino'], experience: 'iniciante', step: 5, completed: true })]
]);
const postKey = 'makerlink.posts.v1.ana_maker';
let app = boot(storage);
const submit = () => app.context.window.MakerLinkContent.submit({ target: app.element('publication-form'), preventDefault() {} }, message => { app.context.feedback = message; });
function fill(overrides = {}) {
  Object.entries({ 'post-type': 'Projeto', 'post-title': 'Meu primeiro sensor', 'post-text': 'Montei um circuito para medir a umidade.\nAgora vou registrar os testes.', 'post-category': 'arduino', 'post-tags': 'ESP32, sensores, #ESP32', ...overrides }).forEach(([id, value]) => { app.element(id).value = value; });
}
app.navigate('publicar');
assert.equal(app.context.location.hash, '#publicar');
assert.equal(app.context.document.title, 'MakerLink · Criar publicação');
assert.match(app.element('#main').innerHTML, /id="publication-form"/);
assert.match(app.element('#main').innerHTML, /Cancelar/);
submit();
for (const id of ['post-type', 'post-title', 'post-text', 'post-category']) assert.equal(app.element(id).attributes['aria-invalid'], 'true');
assert(!storage.has(postKey));
fill({ 'post-title': '  ', 'post-text': '   ', 'post-type': 'Inválido', 'post-category': 'unknown', 'post-tags': '1,2,3,4,5,6' });
submit();
assert(app.element('post-type').focused);
assert.match(app.element('post-tags-error').textContent, /até 5 tags/);
assert(!storage.has(postKey));
fill({ 'post-title': 'x'.repeat(121), 'post-text': 'x'.repeat(5001), 'post-tags': 'x'.repeat(25) });
submit();
assert(!storage.has(postKey));
