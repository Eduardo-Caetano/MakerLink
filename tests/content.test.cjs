assert.equal(storage.get(postKey), '{invalid');
storage.set(postKey, JSON.stringify([{ ...records[0], categoryId: 'invalid' }]));
assert.equal(app.context.window.MakerLinkContent.own(user).length, 0);
app.click('#logout');
app.navigate('publicar');
assert.equal(app.context.location.hash, '#boas-vindas');
submit();
assert.equal(storage.get(postKey), JSON.stringify([{ ...records[0], categoryId: 'invalid' }]));
