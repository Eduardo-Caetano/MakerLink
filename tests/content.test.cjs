submit();
assert.match(app.element('publication-error').textContent, /Não foi possível salvar/);
assert.equal(app.element('post-title').value, 'Meu primeiro sensor');
assert.equal(JSON.parse(storage.get(postKey)).length, 3);
assert.equal(app.element('publication-form [type="submit"]').disabled, false);
app.context.localStorage.setItem = originalSet;
storage.set(postKey, '{invalid');
