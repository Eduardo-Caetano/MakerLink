function signup(app, values) {
  registration(app, values);
  app.submit('register-form');
  app.element('code').value = '123456';
  app.submit('two-factor-form');
  app.navigate(app.context.location.hash.replace(/^#/, ''));
}
function select(app, type, id, checked = true) {
  app.context.window.MakerLinkOnboarding.change({ target: { dataset: { [type === 'interest' ? 'onboardingInterest' : 'onboardingExperience']: id }, checked } }, app.auth.user());
}
function click(app, action, community) {
  const selector = community ? '[data-onboarding-community]' : '[data-onboarding-action]';
  const target = { dataset: community ? { onboardingCommunity: community } : { onboardingAction: action }, classList: { toggle() {} }, setAttribute() {} };
  app.context.window.MakerLinkOnboarding.click({ target: { closest: value => value === selector ? target : null } }, app.auth.user(), () => {});
  app.navigate(app.context.location.hash.replace(/^#/, ''));
  return target;
}
