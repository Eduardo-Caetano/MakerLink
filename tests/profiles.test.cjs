const assert = require('node:assert/strict');
const { boot } = require('./helpers.cjs');
const user = { name: 'Ana Maker', initials: 'AM', username: 'ana_maker', email: 'ana@example.com' };
const preferences = { interests: ['arduino', 'programacao'], communities: ['arduino', 'codigo'], experience: 'avancado', step: 5, completed: true };
const storage = new Map([
  ['makerlink.session.v1', JSON.stringify({ user, expires: Date.now() + 86400000 })],
  ['makerlink.onboarding.v1.ana_maker', JSON.stringify(preferences)]
]);
let app = boot(storage);
const profiles = app.context.window.MakerLinkProfiles;
const data = app.context.window.MakerLinkData;
const icon = () => '';
const connectionKey = 'makerlink.connections.v1.ana_maker';
const feedback = [];
const failures = [];
function connect(id = 'mariana-alves') {
  const button = app.element('connection-button');
  button.dataset = { connect: id };
  app.context.window.MakerLinkProfiles.click({ target: { closest: selector => selector === '[data-connect]' ? button : null } }, app.auth.user(), message => feedback.push(message), (title, text) => failures.push({ title, text }));
  return button;
}
app.navigate('perfil');
let markup = app.element('#main').innerHTML;
assert.match(markup, /Meu perfil/);
assert.match(markup, /Ana Maker/);
assert.match(markup, /Arduino e ESP32/);
assert.match(markup, /Código compartilhado/);
assert.match(markup, /Experiência técnica declarada: <strong>Avançado/);
assert.match(markup, /Ainda não informadas/);
assert.match(markup, /Você ainda não publicou/);
assert.match(markup, /Ainda sem emblemas/);
assert.match(markup, /Aprendiz/);
assert(!markup.includes('ana@example.com'), 'E-mail não é exibido no perfil');
assert(!markup.includes('data-connect='), 'Não permite conectar consigo mesmo');
assert.equal(app.auth.user().experience, 0);
assert.equal(profiles.resolve('perfil', user).connections, 0);
assert.equal(profiles.resolve('perfil/inexistente', user), null);
assert.equal(profiles.resolve('perfil', null), null);
const levels = new Set();
for (const fixture of data.profiles) {
  app.navigate(`perfil/${fixture.id}`);
  const profile = profiles.resolve(`perfil/${fixture.id}`, user);
  levels.add(profile.level);
  markup = app.element('#main').innerHTML;
  assert(profile.name && profile.initials && profile.bio && profile.skills.length);
  assert(profile.publications.every(post => post.authorId === profile.id));
  assert(profile.publications.length > 0);
  assert(fixture.connections >= 0);
  assert(fixture.badges.every(id => data.recognitionBadges[id]));
  assert(fixture.interests.every(id => data.onboardingInterests.some(item => item.id === id)));
  assert(fixture.communities.every(id => data.suggestedCommunities.some(item => item.id === id)));
  assert(markup.includes(`data-connect="${fixture.id}"`));
  assert(markup.includes(`data-profile-post="${profile.publications[0].id}"`));
  assert(markup.includes('Emblemas ilustrativos'));
  assert.equal((markup.match(/aria-current="step"/g) || []).length, 1);
}
assert.deepEqual([...levels].sort(), ['Aprendiz', 'Especialista', 'Maker', 'Mentor']);
app.navigate('perfil/mariana-alves');
const initial = data.profiles.find(profile => profile.id === 'mariana-alves').connections;
const snapshot = JSON.stringify(data.profiles);
const button = connect();
assert.equal(button.attributes['aria-pressed'], 'true');
assert.equal(button.querySelector('span').textContent, 'Desfazer conexão');
assert.equal(app.element('[data-profile-connection-count]').textContent, initial + 1);
assert.deepEqual(JSON.parse(storage.get(connectionKey)), ['mariana-alves']);
assert.equal(feedback.length, 1);
app.navigate('perfil');
assert.match(app.element('#main').innerHTML, /Suas conexões/);
assert.match(app.element('#main').innerHTML, /href="#perfil\/mariana-alves"/);
assert.equal(profiles.resolve('perfil', user).connections, 1);
app = boot(storage);
app.navigate('perfil/mariana-alves');
assert.match(app.element('#main').innerHTML, /data-connect="mariana-alves" aria-pressed="true"/);
connect();
assert.deepEqual(JSON.parse(storage.get(connectionKey)), []);
assert.equal(app.element('[data-profile-connection-count]').textContent, initial);
assert.equal(app.context.window.MakerLinkProfiles.resolve('perfil', user).connections, 0);
assert.equal(JSON.stringify(data.profiles), snapshot, 'Conexão não altera fixtures nem emblemas');
assert.equal(app.auth.user().level, 'Aprendiz');
assert.equal(app.auth.user().experience, 0);
storage.set(connectionKey, JSON.stringify(['mariana-alves', 'mariana-alves', 'desconhecido']));
assert.deepEqual(Array.from(app.context.window.MakerLinkProfiles.connections(user)), ['mariana-alves']);
assert.equal(app.context.window.MakerLinkProfiles.connections({ ...user, username: 'outro' }).length, 0, 'Isola conexões por usuário');
storage.set(connectionKey, '{invalid');
assert.equal(app.context.window.MakerLinkProfiles.connections(user).length, 0);
const originalSet = app.context.localStorage.setItem;
app.context.localStorage.setItem = () => { throw Error('Quota exceeded'); };
connect();
assert.equal(failures.length, 1);
assert.equal(app.context.window.MakerLinkProfiles.connections(user).length, 0);
app.context.localStorage.setItem = originalSet;
app.navigate('perfil');
const before = storage.get(connectionKey);
connect();
assert.equal(storage.get(connectionKey), before, 'Ignora ação de conexão na rota do próprio perfil');
const escaped = app.context.window.MakerLinkProfiles.resolve('perfil', { ...user, name: '<img src=x onerror=alert(1)>' });
const escapedHTML = app.context.window.MakerLinkProfiles.render(escaped, user, icon);
assert(escapedHTML.includes('&lt;img'));
assert(!escapedHTML.includes('<img src=x'));
app.click('#logout');
app.navigate('perfil/mariana-alves');
assert.equal(app.context.location.hash, '#boas-vindas', 'Rotas de terceiros preservam autenticação');
app.click('#demo-login');
app.navigate('perfil');
assert.match(app.element('#main').innerHTML, /Eduardo Costa/);
assert.match(app.element('#main').innerHTML, /Prototipagem/);
assert.match(app.element('#main').innerHTML, /Arduino &amp; ESP32/);
console.log('PASS: perfil próprio integrado, sete perfis, publicações por autor, quatro níveis, emblemas, conexão reversível/persistente, contagens, isolamento, dados inválidos, falha de armazenamento, escape de nomes, autenticação e demonstração.');
